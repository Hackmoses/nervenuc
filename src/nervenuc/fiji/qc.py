@dataclass(frozen=True)
class FijiImportedRoiRecord:
    """Record of an imported ImageJ ROI and its assigned NerveNuc review identifier.

    Attributes:
        roi_name: Original ROI name string from the ImageJ ROI metadata.
        roi_index: 0-based index of the ROI within the imported file/ZIP set.
        review_id: Authoritative NerveNuc review identifier generated by ReviewSession.
        roi_type: Name of the ImageJ ROI type (e.g. 'POLYGON', 'RECT', 'OVAL').
    """

    roi_name: str
    roi_index: int
    review_id: str
    roi_type: str


@dataclass(frozen=True)
class FijiRoiImportResult:
    """Structured result of a manual Fiji ROI import operation.

    Attributes:
        source_path: Path to the imported ImageJ .roi or .zip file.
        roi_file_sha256: SHA-256 hexadecimal digest of the imported ROI file artifact.
        imported: Tuple of FijiImportedRoiRecord objects for all imported ROIs.
    """

    source_path: Path
    roi_file_sha256: str
    imported: tuple[FijiImportedRoiRecord, ...]


@dataclass(frozen=True)
class FijiRoiSplitResult:
    """Structured result of an explicit Fiji-assisted split replacement operation.

    Attributes:
        source_path: Path to the imported ImageJ .roi or .zip file containing replacement ROIs.
        roi_file_sha256: SHA-256 hexadecimal digest of the imported ROI file artifact.
        target_review_id: Identifier of the retired parent nucleus in ReviewSession.
        child_review_ids: Tuple of newly generated EDIT-* review identifiers.
        imported: Tuple of FijiImportedRoiRecord objects for all replacement ROIs.
    """

    source_path: Path
    roi_file_sha256: str
    target_review_id: str
    child_review_ids: tuple[str, ...]
    imported: tuple[FijiImportedRoiRecord, ...]


def _compute_file_sha256(path: Path) -> str:
    """Calculate the SHA-256 hash of a file on disk."""
    hasher = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            hasher.update(chunk)
    return hasher.hexdigest()


def _extract_shape(source: ReviewSession | ReviewedSegmentationResult) -> tuple[int, int]:
    """Derive authoritative 2D (H, W) shape from a ReviewSession or ReviewedSegmentationResult."""
    if isinstance(source, ReviewedSegmentationResult):
        return source.labels.shape
    if isinstance(source, ReviewSession):
        # Derive from the authoritative source segmentation result or session shape attribute
        if hasattr(source, "_source_result") and hasattr(source._source_result, "labels"):
            return source._source_result.labels.shape
        if hasattr(source, "_shape"):
            return source._shape
    raise InvalidReviewOperationError(
        f"Expected ReviewSession or ReviewedSegmentationResult, got {type(source).__name__}."
    )


def export_review_rois(
    source: ReviewSession | ReviewedSegmentationResult,
    output_path: Path | str,
    overwrite: bool = False,
) -> Path:
    """Export active 2D QC segmentation objects to a Fiji ImageJ ROI set ZIP file.

    Export semantics:
        - ReviewedSegmentationResult: Exports active finalized objects.
        - ReviewSession: Exports current active objects only (QC-in-progress).
        - Retired, rejected, or deleted objects are strictly excluded.
        - Every ROI is named with the exact NerveNuc review identifier (e.g. 'AUTO-000001', 'MAN-000001', 'EDIT-000001').
        - Atomic conversion: All active objects are converted and validated in memory first.
          If any object fails conversion (e.g. multi-component mask or topological hole),
          export fails immediately and no output file is written.

    Args:
        source: Active ReviewSession or finalized ReviewedSegmentationResult.
        output_path: Target path for the exported .zip file.
        overwrite: If False and output_path exists, raises NerveNucFijiError.

    Returns:
        Path to the successfully written ROI set ZIP.

    Raises:
        InvalidReviewOperationError: If source is not a supported session or result.
        NerveNucFijiError: If no active objects exist, target exists with overwrite=False, or write fails.
        InvalidRoiGeometryError: If an active mask cannot be safely converted to a polygon ROI.
    """
    out_p = Path(output_path)
    if out_p.exists() and not overwrite:
        raise NerveNucFijiError(f"Target ROI file '{out_p}' already exists and overwrite is False.")

    # Collect (review_id, mask) pairs
    items_to_convert: list[tuple[str, np.ndarray]] = []

    if isinstance(source, ReviewedSegmentationResult):
        if source.objects.empty or not np.any(source.labels > 0):
            raise NerveNucFijiError("Cannot export empty ROI collection: no active objects found in reviewed result.")
        for row in source.objects.itertuples(index=False):
            mask = (source.labels == row.current_label)
            items_to_convert.append((row.review_id, mask))

    elif isinstance(source, ReviewSession):
        active_objects = getattr(source, "_active_objects", None)
        if active_objects is None or len(active_objects) == 0:
            raise NerveNucFijiError("Cannot export empty ROI collection: no active objects found in ReviewSession.")
        for rid, rec in active_objects.items():
            items_to_convert.append((rid, rec.mask))

    else:
        raise InvalidReviewOperationError(
            f"source must be a ReviewSession or ReviewedSegmentationResult, got {type(source).__name__}."
        )

    # Atomic conversion of all active masks in memory
    rois: list[roifile.ImagejRoi] = []
    for rid, mask in items_to_convert:
        roi = mask_to_roi(mask, name=rid)
        rois.append(roi)

    # Write atomically
    write_roi_set(rois, out_p, overwrite=overwrite)
    return out_p


def import_rois_as_manual(
    review_session: ReviewSession,
    roi_path: Path | str,
    source_shape: tuple[int, int] | None = None,
) -> FijiRoiImportResult:
    """Import an ImageJ ROI or ROI set ZIP into an active ReviewSession as manual objects.

    Security and Integrity Rules:
        - All imported ROIs enter strictly via ReviewSession.add(), generating authoritative
          MAN-xxxxxx identifiers, review_origin='manual_add', and review_status='edited'.
        - ROI names in the file (even if named 'AUTO-000001') are treated as untrusted metadata
          and cannot hijack or overwrite existing objects.
        - Provenance notes record the ROI file name, ROI name, index, and artifact SHA-256 hash.
        - Raw microscopy image source identity (source_id, source_hash) remains unchanged.
        - Atomic validation: All ROIs are read, type-validated, rasterized, and preflight-checked
          against ReviewSession.add() constraints before any mutation occurs. If any ROI fails,
          the ReviewSession remains completely unmodified.

    Args:
        review_session: Active ReviewSession instance.
        roi_path: Path to an ImageJ .roi or .zip file.
        source_shape: Optional expected (H, W) shape for explicit validation against session shape.

    Returns:
        FijiRoiImportResult containing file hash and records of all added objects.

    Raises:
        InvalidReviewOperationError: If review_session is not a valid ReviewSession.
        InvalidRoiGeometryError: If source_shape mismatches session shape or ROI rasterization fails.
        UnsupportedRoiError: If an ROI type is unsupported for nuclear QC.
        InvalidReviewMaskError: If an imported mask fails M3 ReviewSession.add() validation or collides.
        NerveNucFijiError: If the ROI file is missing or corrupt.
    """
    if not isinstance(review_session, ReviewSession):
        raise InvalidReviewOperationError(
            f"review_session must be a ReviewSession, got {type(review_session).__name__}."
        )

    session_shape = _extract_shape(review_session)
    if source_shape is not None and source_shape != session_shape:
        raise InvalidRoiGeometryError(
            f"Provided source_shape {source_shape} does not match ReviewSession shape {session_shape}."
        )

    p = Path(roi_path)
    if not p.is_file():
        raise NerveNucFijiError(f"ROI file not found: {p}")

    file_sha256 = _compute_file_sha256(p)
    raw_rois = read_roi_set(p)
    if not raw_rois:
        raise NerveNucFijiError(f"No ROIs found in '{p}'.")

    # Step 1: Pre-validate ROI types and rasterize all ROIs in memory
    candidate_items: list[tuple[int, roifile.ImagejRoi, np.ndarray, str, str]] = []
    for idx, roi in enumerate(raw_rois):
        validate_roi_type(roi)
        mask = rasterize_roi(roi, shape=session_shape)
        roi_name = getattr(roi, "name", None) or f"ROI_{idx + 1}"
        provenance_note = (
            f"Imported from Fiji ROI set: {p.name}; ROI: {roi_name}; "
            f"ROI index: {idx}; ROI SHA256: {file_sha256}"
        )
        candidate_items.append((idx, roi, mask, roi_name, provenance_note))

    # Step 2: Preflight check against ReviewSession.add() invariants to guarantee atomicity
    active_objects = getattr(review_session, "_active_objects", {})
    cumulative_masks: list[np.ndarray] = []

    for idx, roi, mask, roi_name, _ in candidate_items:
        if not np.any(mask):
            raise InvalidRoiGeometryError(
                f"ROI {idx} ('{roi_name}') produced empty rasterization (0 positive pixels)."
            )
        # Check collision with current active session objects (ReviewSession.add rule)
        for act_id, act_rec in active_objects.items():
            if np.any(np.logical_and(mask, act_rec.mask)):
                raise InvalidReviewMaskError(
                    f"Manual mask overlaps with existing active nucleus '{act_id}'."
                )
        # Check collision with earlier candidate masks in this batch (ReviewSession.add rule)
        for prev_idx, prev_mask in enumerate(cumulative_masks):
            if np.any(np.logical_and(mask, prev_mask)):
                raise InvalidReviewMaskError(
                    f"Manual mask at index {idx} overlaps with manual mask at index {prev_idx}."
                )
        cumulative_masks.append(mask)

    # Step 3: All preflight checks passed. Execute ReviewSession.add() sequentially.
    imported_records: list[FijiImportedRoiRecord] = []
    for idx, roi, mask, roi_name, prov_note in candidate_items:
        new_id = review_session.add(mask, note=prov_note)
        roi_type_name = getattr(roi.roitype, "name", str(roi.roitype))
        imported_records.append(
            FijiImportedRoiRecord(
                roi_name=roi_name,
                roi_index=idx,
                review_id=new_id,
                roi_type=roi_type_name,
            )
        )

    return FijiRoiImportResult(
        source_path=p,
        roi_file_sha256=file_sha256,
        imported=tuple(imported_records),
    )


def replace_with_fiji_rois(
    review_session: ReviewSession,
    target_review_id: str,
    roi_path: Path | str,
    source_shape: tuple[int, int] | None = None,
    note: str | None = None,
) -> FijiRoiSplitResult:
    """Replace an active nucleus in ReviewSession using 2 or more Fiji ROIs via ReviewSession.split().

    Semantics:
        - Uses authoritative ReviewSession.split(), retiring the target parent with
          retirement_reason='split' and allocating EDIT-xxxxxx child identifiers.
        - Cardinality: Requires at least 2 replacement ROIs (as required by M3 split contract).
        - Boundary & Overlap: Delegated entirely to ReviewSession.split() authoritative rules.
        - Provenance notes record target review ID, replacement ROI names, file name, and SHA-256 hash.

    Args:
        review_session: Active ReviewSession instance.
        target_review_id: Identifier of the active nucleus to replace.
        roi_path: Path to an ImageJ .roi or .zip file containing replacement ROIs.
        source_shape: Optional expected (H, W) shape for validation against session shape.
        note: Optional additional commentary from caller.

    Returns:
        FijiRoiSplitResult containing split details and child review records.

    Raises:
        InvalidReviewOperationError: If review_session is invalid or target nucleus is not active.
        UnknownReviewObjectError: If target_review_id does not exist in the session.
        InvalidReviewMaskError: If replacement ROIs fail M3 split constraints (<2 ROIs, exceed parent, overlap).
        UnsupportedRoiError: If an ROI type is unsupported.
        InvalidRoiGeometryError: If source_shape mismatches or ROI geometry is invalid.
        NerveNucFijiError: If the ROI file is missing or corrupt.
    """
    if not isinstance(review_session, ReviewSession):
        raise InvalidReviewOperationError(
            f"review_session must be a ReviewSession, got {type(review_session).__name__}."
        )

    session_shape = _extract_shape(review_session)
    if source_shape is not None and source_shape != session_shape:
        raise InvalidRoiGeometryError(
            f"Provided source_shape {source_shape} does not match ReviewSession shape {session_shape}."
        )

    p = Path(roi_path)
    if not p.is_file():
        raise NerveNucFijiError(f"ROI file not found: {p}")

    file_sha256 = _compute_file_sha256(p)
    raw_rois = read_roi_set(p)
    if not raw_rois:
        raise NerveNucFijiError(f"No ROIs found in '{p}'.")

    if len(raw_rois) < 2:
        raise InvalidReviewMaskError(
            f"Split replacement requires at least 2 replacement ROIs, got {len(raw_rois)} in '{p.name}'."
        )

    # Pre-validate ROI types and rasterize all ROIs in memory
    replacement_masks: list[np.ndarray] = []
    imported_rois: list[tuple[int, roifile.ImagejRoi, str, str]] = []
    for idx, roi in enumerate(raw_rois):
        validate_roi_type(roi)
        mask = rasterize_roi(roi, shape=session_shape)
        roi_name = getattr(roi, "name", None) or f"ROI_{idx + 1}"
        roi_type_name = getattr(roi.roitype, "name", str(roi.roitype))
        replacement_masks.append(mask)
        imported_rois.append((idx, roi, roi_name, roi_type_name))

    # Construct split provenance note
    roi_names_str = ", ".join(name for _, _, name, _ in imported_rois)
    fiji_note = (
        f"Split replacement from Fiji ROI set: {p.name}; ROIs: [{roi_names_str}]; "
        f"ROI SHA256: {file_sha256}"
    )
    full_note = f"{note} | {fiji_note}" if note else fiji_note

    # Call authoritative ReviewSession.split()
    child_ids = review_session.split(
        target_review_id,
        replacement_masks=replacement_masks,
        note=full_note,
    )

    # Build return records
    imported_records = tuple(
        FijiImportedRoiRecord(
            roi_name=roi_name,
            roi_index=idx,
            review_id=child_id,
            roi_type=roi_type_name,
        )
        for (idx, roi, roi_name, roi_type_name), child_id in zip(imported_rois, child_ids)
    )

    return FijiRoiSplitResult(
        source_path=p,
        roi_file_sha256=file_sha256,
        target_review_id=target_review_id,
        child_review_ids=child_ids,
        imported=imported_records,
    )
