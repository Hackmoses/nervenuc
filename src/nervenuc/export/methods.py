"""Methods-ready factual summary text generator for reproducible analysis exports."""

from __future__ import annotations

from datetime import datetime, timezone
import platform
import sys
from typing import Any, Mapping, Sequence

import numpy as np
import pandas as pd
import scipy
import skimage


def capture_runtime_environment() -> dict[str, str]:
    """Capture runtime platform and core scientific library versions."""
    import nervenuc

    return {
        "python_version": sys.version.split()[0],
        "platform": platform.platform(),
        "os": platform.system(),
        "numpy_version": np.__version__,
        "scipy_version": scipy.__version__,
        "skimage_version": skimage.__version__,
        "scikit_image_version": skimage.__version__,
        "pandas_version": pd.__version__,
        "nervenuc_version": getattr(nervenuc, "__version__", "unknown"),
    }


def generate_methods_summary(
    config: Any,
    provenance_list: Sequence[Any] | None = None,
    qc_records: Sequence[Any] | None = None,
    modality: str = "direct_2d",
    animal_count: int | None = None,
    sample_count: int | None = None,
) -> str:
    """Generate a methods-ready factual summary describing the exact completed analysis.

    Args:
        config: AnalysisConfig or VolumeAnalysisConfig instance.
        provenance_list: Optional sequence of ImageSourceProvenance / VolumeSourceProvenance records.
        qc_records: Optional sequence of QCSummaryRecord objects or dictionaries.
        modality: "direct_2d", "projected_2d", or "volume_3d".
        animal_count: Number of biological replicate animals (or None if unassigned).
        sample_count: Total number of technical image/volume observations.

    Returns:
        Structured plain-text methods narrative suitable for adaptation in a scientific paper.
    """
    env = capture_runtime_environment()
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    effective_sample_count = sample_count if sample_count is not None else (len(provenance_list) if provenance_list else 1)

    lines: list[str] = []
    lines.append("Quantitative Microscopy Analysis Methods Summary")
    lines.append(f"Generated by NerveNuc (v{env['nervenuc_version']}) on {now_str}")
    lines.append("=" * 60)
    lines.append("")

    # 1. Software & Environment
    lines.append("1. Software & Environment")
    lines.append(
        f"Quantitative image analysis was performed using NerveNuc version {env['nervenuc_version']} "
        f"running on {env['platform']} (Python {env['python_version']}, NumPy {env['numpy_version']}, "
        f"SciPy {env['scipy_version']}, scikit-image {env['scikit_image_version']}, Pandas {env['pandas_version']})."
    )
    lines.append("")

    # 2. Modality & Optical Preparation
    lines.append("2. Image Modality & Optical Preparation")
    if modality == "direct_2d":
        lines.append(
            f"Analysis was performed directly on single-plane 2D fluorescence micrographs ({effective_sample_count} fields of view)."
        )
    elif modality == "projected_2d":
        # Extract projection metadata from provenance if available
        proj_methods: set[str] = set()
        z_ranges: list[str] = []
        z_steps: list[float] = []
        if provenance_list:
            for p in provenance_list:
                pm = getattr(p, "projection_method", None)
                if pm:
                    proj_methods.add(str(pm))
                zs = getattr(p, "z_start", None)
                ze = getattr(p, "z_stop", None)
                if zs is not None and ze is not None:
                    z_ranges.append(f"zero-based slices [{zs}, {ze})")
                pz = getattr(p, "physical_size_z_um", None)
                if pz is not None:
                    z_steps.append(pz)

        pm_str = "/".join(sorted(proj_methods)) if proj_methods else "maximum"
        zr_str = f" across {z_ranges[0]}" if z_ranges else ""
        step_str = f" (Z-step: {z_steps[0]:.3f} µm)" if z_steps else ""
        lines.append(
            f"3D optical Z-stacks ({effective_sample_count} acquisitions) were projected to 2D using "
            f"{pm_str} intensity projection{zr_str}{step_str} prior to nuclear segmentation."
        )
    elif modality == "volume_3d":
        # Extract 3D spacing from provenance if available
        spacing_str = ""
        if provenance_list and len(provenance_list) > 0:
            sp = getattr(provenance_list[0], "spacing", None)
            if sp is not None:
                sz = getattr(sp, "z", None)
                sy = getattr(sp, "y", None)
                sx = getattr(sp, "x", None)
                if sz is not None and sy is not None and sx is not None:
                    spacing_str = f" (voxel spacing: {sz:.3f} × {sy:.3f} × {sx:.3f} µm)"
        calibration_desc = (
            "calibrated Z-stack volumes"
            if spacing_str
            else "Z-stack volumes without complete physical voxel calibration"
        )
        lines.append(
            f"True 3D volumetric analysis was performed on {calibration_desc}{spacing_str} "
            f"across {effective_sample_count} acquisitions."
        )
    else:
        lines.append(f"Analysis was performed using {modality} mode across {effective_sample_count} acquisitions.")
    lines.append("")

    # 3. Nuclear Segmentation & Quality Control
    lines.append("3. Nuclear Segmentation & Quality Control")
    seg = getattr(config, "segmentation", None)
    if seg is not None:
        # Check 2D vs 3D segmentation config attributes
        th_method = getattr(seg, "threshold_method", "otsu")
        if th_method == "manual":
            m_th = getattr(seg, "manual_threshold", None)
            th_desc = f"manual intensity thresholding ({m_th})"
        elif th_method == "otsu":
            th_desc = "Otsu automated thresholding"
        elif th_method == "li":
            th_desc = "Li minimum cross-entropy automated thresholding"
        else:
            th_desc = f"{th_method} thresholding"

        # Smoothing
        g_sigma = getattr(seg, "gaussian_sigma", None)
        g_sigma_xy = getattr(seg, "gaussian_sigma_xy_px", None)
        g_sigma_z = getattr(seg, "gaussian_sigma_z_slices", None)
        if g_sigma is not None:
            smooth_desc = f"Gaussian smoothing (σ = {g_sigma} px)" if g_sigma > 0 else "without Gaussian smoothing"
        elif g_sigma_xy is not None:
            if g_sigma_xy > 0 or (g_sigma_z is not None and g_sigma_z > 0):
                z_desc = f", σ_z = {g_sigma_z} slices" if g_sigma_z is not None else ""
                smooth_desc = f"Gaussian smoothing (σ_xy = {g_sigma_xy} px{z_desc})"
            else:
                smooth_desc = "without Gaussian smoothing"
        else:
            smooth_desc = "Gaussian smoothing"

        # Watershed & size filters
        min_dist = getattr(seg, "min_distance_px", None)
        min_dist_xy = getattr(seg, "min_distance_xy_px", None)
        watershed_desc = ""
        if min_dist is not None:
            watershed_desc = f" followed by distance-transform watershed separation (min seed distance = {min_dist} px)"
        elif min_dist_xy is not None:
            min_dist_z = getattr(seg, "min_distance_z_slices", None)
            z_seed_desc = f", Z = {min_dist_z} slices" if min_dist_z is not None else ""
            watershed_desc = (
                f" followed by 3D distance-transform watershed separation "
                f"(minimum seed distance: XY = {min_dist_xy} px{z_seed_desc})"
            )

        # Size filter bounds
        min_area = getattr(seg, "min_area_px", None)
        max_area = getattr(seg, "max_area_px", None)
        min_vol = getattr(seg, "min_volume_voxels", None)
        max_vol = getattr(seg, "max_volume_voxels", None)

        size_desc = ""
        if min_area is not None:
            max_s = f" and maximum area {max_area} px²" if max_area is not None else ""
            size_desc = f" Objects with area below {min_area} px²{max_s} were excluded."
        elif min_vol is not None:
            max_v = f" and maximum volume {max_vol} voxels" if max_vol is not None else ""
            size_desc = f" Objects with volume below {min_vol} voxels{max_v} were excluded."

        border_desc = ""
        if getattr(seg, "exclude_border", False):
            border_desc = " Border-touching nuclei were excluded from downstream analysis."
        elif hasattr(seg, "exclude_xy_border"):
            excluded_boundaries = []
            if getattr(seg, "exclude_xy_border", False):
                excluded_boundaries.append("XY")
            if getattr(seg, "exclude_z_border", False):
                excluded_boundaries.append("Z")
            if excluded_boundaries:
                border_desc = f" Nuclei touching {' and '.join(excluded_boundaries)} volume boundaries were excluded."
            else:
                border_desc = " Border-touching nuclei were retained."

        hole_desc = (
            " Enclosed foreground holes were filled."
            if getattr(seg, "fill_holes", False)
            else " Enclosed foreground holes were not filled."
        )

        lines.append(
            f"Nuclear instances were segmented from the nuclear channel using {th_desc} with {smooth_desc}{watershed_desc}.{hole_desc}{size_desc}{border_desc}"
        )
    else:
        lines.append("Nuclear instances were segmented using configured parameters.")

    # QC Summary facts
    if qc_records:
        total_accepted = sum(getattr(q, "accepted_count", 0) for q in qc_records)
        total_added = sum(getattr(q, "added_count", 0) for q in qc_records)
        total_rejected = sum(getattr(q, "rejected_count", 0) for q in qc_records)
        total_final = sum(getattr(q, "final_count", 0) for q in qc_records)
        review_states = {getattr(q, "review_state", "unknown") for q in qc_records}
        counts_text = (
            f"{total_final} total nuclei were finalized for analysis ({total_accepted} accepted, "
            f"{total_added} manually added, {total_rejected} rejected across {len(qc_records)} images)."
        )
        if review_states == {"auto_accepted"}:
            lines.append(
                "Segmentation candidates were automatically accepted without manual per-object QC during the batch run; "
                + counts_text
            )
        elif "auto_accepted" in review_states:
            lines.append(
                "The study contains mixed QC policies, including auto-accepted samples without manual per-object QC; "
                + counts_text
            )
        else:
            lines.append("Segmentations underwent finalized quality control before quantification: " + counts_text)
    lines.append("")

    # 4. Marker Quantification & Threshold Criteria
    lines.append("4. Marker Quantification & Threshold Criteria")
    thresholds = getattr(config, "thresholds", ())
    if thresholds:
        lines.append("Fluorescence signal within segmented nuclear regions was quantified and binarized using defined thresholds:")
        for t in thresholds:
            m_name = getattr(t, "marker_name", "Unknown")
            meas = getattr(t, "measurement", "mean_intensity")
            op = getattr(t, "comparison", getattr(t, "operator", ">="))
            val = getattr(t, "threshold", getattr(t, "threshold_value", getattr(t, "value", 0.0)))
            lines.append(f"- {m_name}: {meas} {op} {val}")
    else:
        lines.append("Marker signal quantification was performed using configured channel measurements.")
    lines.append("")

    # 5. Biological Replicate Aggregation
    lines.append("5. Biological Replicate Aggregation")
    if animal_count is not None and animal_count > 0:
        lines.append(
            f"Analysis was performed at the single-nucleus level across {effective_sample_count} technical image observations "
            f"from {animal_count} biological replicates (animals). For animal-level biological quantification, raw numerators "
            f"and raw denominators were pooled across all images for each animal before calculating biological percentages:"
        )
        lines.append("    Animal Percentage = 100 × (Σ raw numerators across images) / (Σ raw denominators across images)")
        lines.append("Image-level percentages were not averaged, preserving proper biological weighting.")
    else:
        lines.append(
            f"Quantification was performed at the single-nucleus level across {effective_sample_count} observation(s)."
        )
    lines.append("")

    return "\n".join(lines)
